#!/usr/bin/env python3
"""Optional builder for a real DEIS-derived weekly panel.

The bundled Chile-ED-Resp benchmark is synthetic. This optional script downloads the
official Chilean open-data Parquet resource and creates a separate real-data panel.
Any output generated by this script inherits the source portal's CC BY-NC terms and
must be reviewed before redistribution.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import pandas as pd

DEIS_URL = "https://datos.gob.cl/dataset/606ef5bb-11d1-475b-b69f-b980da5757f4/resource/ae6c9887-106d-4e98-8875-40bf2b836041/download/at_urg_respiratorio_semanal.parquet"
CAUSE_PATTERNS = {
    "high_respiratory_infection": r"IRA\s*Alta|Infecci[oó]n Respiratoria Aguda Alta|J00\s*[-–]\s*J06",
    "influenza": r"Influenza|J09\s*[-–]\s*J11",
    "pneumonia": r"Neumon[ií]a|J12\s*[-–]\s*J18",
    "bronchial_crisis": r"Crisis Bronquial|Asma|J40\s*[-–]\s*J46",
    "other_respiratory": r"Otra.*Respir",
    "covid19_identified": r"COVID.*identificad",
    "covid19_unidentified": r"COVID.*no identificad|COVID.*sin identific",
}


def normalize_cause(value: str) -> str | None:
    text = str(value)
    for normalized, pattern in CAUSE_PATTERNS.items():
        if re.search(pattern, text, flags=re.IGNORECASE):
            return normalized
    return None


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="data/deis_real_weekly_panel.csv")
    parser.add_argument("--top-sites", type=int, default=9)
    args = parser.parse_args()
    try:
        raw = pd.read_parquet(DEIS_URL)
    except ImportError as error:
        raise SystemExit("Install pyarrow first: python -m pip install pyarrow") from error
    required = {"EstablecimientoCodigo", "EstablecimientoGlosa", "TipoUrgencia", "Anio", "SemanaEstadistica", "Causa", "NumTotal"}
    missing = sorted(required.difference(raw.columns))
    if missing:
        raise SystemExit(f"Source schema changed; missing columns: {missing}")
    data = raw.loc[raw["Anio"].between(2022, 2025)].copy()
    data = data.loc[data["TipoUrgencia"].astype(str).str.contains("Hospitalaria|UEH", case=False, na=False)].copy()
    data["normalized_cause"] = data["Causa"].map(normalize_cause)
    data = data.dropna(subset=["normalized_cause"])
    pivot = data.pivot_table(index=["EstablecimientoCodigo", "EstablecimientoGlosa", "Anio", "SemanaEstadistica"], columns="normalized_cause", values="NumTotal", aggfunc="sum", fill_value=0).reset_index()
    target = "high_respiratory_infection"
    top_codes = pivot.groupby("EstablecimientoCodigo")[target].sum().nlargest(args.top_sites).index
    panel = pivot.loc[pivot["EstablecimientoCodigo"].isin(top_codes)].copy()
    panel = panel.rename(columns={"EstablecimientoCodigo": "site_code", "EstablecimientoGlosa": "site_name", "Anio": "year", "SemanaEstadistica": "epi_week"})
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    panel.to_csv(output, index=False)
    print(f"Wrote {len(panel):,} real-source rows to {output}")


if __name__ == "__main__":
    main()
